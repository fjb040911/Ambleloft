import {test,expect} from '@playwright/test';
for(const layoutMode of ['activity','classic'])test(`${layoutMode}: resize home and settings sidebars independently`,async({page})=>{
 await page.addInitScript(({layoutMode})=>{if(!localStorage.getItem('atelier.workspace.v1'))localStorage.setItem('atelier.workspace.v1',JSON.stringify({tasks:[],projects:[],theme:'light',language:'zh-CN',layoutMode}));},{layoutMode});
 await page.goto('/');
 const home=page.getByRole('separator',{name:'调整首页侧栏宽度'});
 const sidebar=page.locator('.workspace-sidebar-container');
 const initial=layoutMode==='activity'?256:224;
 await expect(sidebar).toHaveCSS('width',`${initial}px`);
 const box=(await home.boundingBox())!;
 await page.mouse.move(box.x+3,box.y+100);await page.mouse.down();await page.mouse.move(box.x+83,box.y+100,{steps:8});await page.mouse.up();
 await expect(sidebar).toHaveCSS('width',`${initial+80}px`);
 await expect(page.locator('[data-slot=sidebar-gap]')).toHaveCSS('width',`${initial+80}px`);
 await home.press('ArrowRight');await expect(sidebar).toHaveCSS('width',`${initial+88}px`);
 await page.reload();await expect(sidebar).toHaveCSS('width',`${initial+88}px`);
 await page.getByRole('button',{name:'隐藏侧栏',exact:true}).click();await expect(sidebar).toHaveAttribute('inert','');await expect(page.locator('[data-slot=sidebar-gap]')).toHaveCSS('width','0px');
 await page.getByRole('button',{name:'显示侧栏',exact:true}).click();await expect(sidebar).toHaveCSS('width',`${initial+88}px`);
 await page.getByRole('button',{name:'设置',exact:true}).click();
 const settings=page.getByRole('separator',{name:'调整设置侧栏宽度'});
 const settingsSidebar=page.locator('#settings-sidebar');await expect(settingsSidebar).toHaveCSS('width','224px');
 const sb=(await settings.boundingBox())!;await page.mouse.move(sb.x+3,sb.y+100);await page.mouse.down();await page.mouse.move(sb.x+67,sb.y+100,{steps:8});await page.mouse.up();
 await expect(settingsSidebar).toHaveCSS('width','288px');
 await settings.press('End');await expect(settingsSidebar).toHaveCSS('width','360px');
 await settings.press('Home');await expect(settingsSidebar).toHaveCSS('width','180px');
 await settings.dblclick();await expect(settingsSidebar).toHaveCSS('width','224px');
 await settings.press('ArrowRight');await expect(settingsSidebar).toHaveCSS('width','232px');
 await page.screenshot({path:`test-results/sidebar-resize-${layoutMode}-settings.png`,animations:'disabled'});
 await page.getByRole('button',{name:'深色',exact:true}).click();
 await page.screenshot({path:`test-results/sidebar-resize-${layoutMode}-settings-dark.png`,animations:'disabled'});
 await page.getByRole('button',{name:'返回应用',exact:true}).click();await expect(sidebar).toHaveCSS('width',`${initial+88}px`);
 await page.getByRole('button',{name:'设置',exact:true}).click();await expect(settingsSidebar).toHaveCSS('width','232px');
 await page.getByRole('button',{name:'返回应用',exact:true}).click();await expect(page.getByRole('button',{name:'设置',exact:true})).toBeFocused();await home.press('End');await expect(sidebar).toHaveCSS('width','420px');
 await page.setViewportSize({width:800,height:840});await expect(sidebar).toHaveCSS('width',layoutMode==='activity'?'340px':'400px');
 await page.setViewportSize({width:1240,height:840});await expect(sidebar).toHaveCSS('width','420px');
 await home.dblclick();await expect(sidebar).toHaveCSS('width',`${initial}px`);
 await page.screenshot({path:`test-results/sidebar-resize-${layoutMode}-home.png`,animations:'disabled'});
 await page.setViewportSize({width:600,height:840});await expect(home).toHaveCount(0);
});
